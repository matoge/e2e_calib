"""Multi-frame BA with perturbed intrinsic: fx-scale AND KB-radial distortion.

Hypothesis test: if the BA solver's camera model is slightly wrong (wrong fx,
or missing KB distortion), does the shared multi-frame extrinsic still
recover the GT perturbation?

Setup (same as ba_multiframe):
  • Scene 015, N=10 consecutive val frames.
  • Sample ONE shared cam-frame rig drift (ypr_cam, t_cam).
  • For each frame run CalibNetDepth → per-point Gaussians (using TRUE K).
  • BA solves one 6-DoF θ shared across all frames, using a PERTURBED K model.
  • Vary perturbation: fx-scale δ, KB-radial k2.

Output: experiments/all_v3_mc/ba_kb/summary.json + hero.png
"""
